poet_name = input("Enter Poet Name : ")
if poet_name == "ghalib".strip().lower():
    print("                                       ======= Mirza Ghalib Says =======\n")
    print("                               Hum  ko  maloom  hai   jannat  ki  haqeeqat  lekin")
    print("                               Dil ke khush rakhne ko Ghalib yeh khayal accha hai")
    print()
elif poet_name == "faraz".strip().lower():
    print("                                       ====== Ahmed Faraz Says ======\n")
    print("                                       Zindagi se yahi gila hai mujhe")
    print("                                       Tu bohat der se mila hai mujhe")
    print()
